-- -----------------------------------------------------------------------------
-- 1. Tipos ENUM para el dominio farmacológico, patológico y de inmunizaciones
-- -----------------------------------------------------------------------------
DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_type WHERE typname = 'e_prescription_status') THEN
    CREATE TYPE e_prescription_status AS ENUM ('active', 'completed', 'suspended', 'cancelled');
  END IF;

  IF NOT EXISTS (SELECT 1 FROM pg_type WHERE typname = 'e_administration_status') THEN
    CREATE TYPE e_administration_status AS ENUM ('scheduled', 'administered', 'omitted', 'refused');
  END IF;

  IF NOT EXISTS (SELECT 1 FROM pg_type WHERE typname = 'e_condition_status') THEN
    CREATE TYPE e_condition_status AS ENUM ('active', 'inactive', 'resolved', 'remission');
  END IF;

  IF NOT EXISTS (SELECT 1 FROM pg_type WHERE typname = 'e_condition_severity') THEN
    CREATE TYPE e_condition_severity AS ENUM ('mild', 'moderate', 'severe');
  END IF;

  IF NOT EXISTS (SELECT 1 FROM pg_type WHERE typname = 'e_administration_route') THEN
    CREATE TYPE e_administration_route AS ENUM (
      'oral', 'sublingual', 'intramuscular', 'intravenous', 'subcutaneous',
      'topical', 'inhalation', 'ophthalmic', 'otic', 'nasal', 'rectal', 'other'
    );
  END IF;

  IF NOT EXISTS (SELECT 1 FROM pg_type WHERE typname = 'e_vaccine_dose') THEN
    CREATE TYPE e_vaccine_dose AS ENUM ('1st', '2nd', '3rd', 'booster', 'annual', 'single');
  END IF;
END;
$$;

-- -----------------------------------------------------------------------------
-- 2. Catálogo Maestro CIE-10 / ICD-10 (health_icd10 en GNU Health)
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.icd10_catalog (
  id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code        VARCHAR(10) NOT NULL UNIQUE,
  description VARCHAR(255) NOT NULL,
  category    VARCHAR(120) NOT NULL,
  is_active   BOOLEAN NOT NULL DEFAULT TRUE,
  created_at  TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_icd10_code ON public.icd10_catalog (code);
CREATE INDEX IF NOT EXISTS idx_icd10_category ON public.icd10_catalog (category);

-- -----------------------------------------------------------------------------
-- 3. Condiciones y Diagnósticos del Paciente (health_disease en GNU Health)
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.patient_conditions (
  id                    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_older_adult        INTEGER NOT NULL,
  id_icd10              INTEGER,
  custom_diagnosis_name VARCHAR(255),
  status                e_condition_status NOT NULL DEFAULT 'active',
  severity              e_condition_severity NOT NULL DEFAULT 'moderate',
  onset_date            DATE,
  resolved_date         DATE,
  notes                 TEXT,
  created_at            TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at            TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_pc_older_adult FOREIGN KEY (id_older_adult) REFERENCES public.older_adult (id) ON DELETE CASCADE,
  CONSTRAINT fk_pc_icd10       FOREIGN KEY (id_icd10)       REFERENCES public.icd10_catalog (id) ON DELETE RESTRICT
);

CREATE INDEX IF NOT EXISTS idx_patientconditions_older_adult ON public.patient_conditions (id_older_adult);
CREATE INDEX IF NOT EXISTS idx_patientconditions_icd10 ON public.patient_conditions (id_icd10);
CREATE INDEX IF NOT EXISTS idx_patientconditions_status ON public.patient_conditions (status);

DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_trigger
    WHERE tgname = 'trg_patient_conditions_updated_at'
      AND tgrelid = 'public.patient_conditions'::regclass
      AND NOT tgisinternal
  ) THEN
    CREATE TRIGGER trg_patient_conditions_updated_at
      BEFORE UPDATE ON public.patient_conditions
      FOR EACH ROW EXECUTE FUNCTION public.set_updated_at();
  END IF;
END;
$$;

-- -----------------------------------------------------------------------------
-- 4. Catálogo Maestro de Medicamentos / Vademécum (gnuhealth_medicament)
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.medication_catalog (
  id                  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name                VARCHAR(150) NOT NULL,
  active_substance    VARCHAR(150) NOT NULL,
  concentration       VARCHAR(80) NOT NULL,
  pharmaceutical_form VARCHAR(80) NOT NULL,
  default_route       e_administration_route NOT NULL DEFAULT 'oral',
  is_active           BOOLEAN NOT NULL DEFAULT TRUE,
  created_at          TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_medcatalog_name ON public.medication_catalog (name);
CREATE INDEX IF NOT EXISTS idx_medcatalog_substance ON public.medication_catalog (active_substance);

-- -----------------------------------------------------------------------------
-- 5. Prescripciones Médicas / Órdenes (gnuhealth_prescription)
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.medication_prescriptions (
  id                    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_older_adult        INTEGER NOT NULL,
  id_medication         INTEGER,
  custom_medication_name VARCHAR(255),
  dosage                VARCHAR(100) NOT NULL,
  route                 e_administration_route NOT NULL DEFAULT 'oral',
  frequency_hours       SMALLINT,
  specific_schedule     VARCHAR(120),
  treatment_type        e_medication_treatment_type NOT NULL DEFAULT 'chronic',
  status                e_prescription_status NOT NULL DEFAULT 'active',
  start_date            DATE NOT NULL,
  end_date              DATE,
  instructions          TEXT,
  prescribed_by         INTEGER,
  is_prn                BOOLEAN NOT NULL DEFAULT FALSE,
  created_at            TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at            TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_mp_older_adult FOREIGN KEY (id_older_adult) REFERENCES public.older_adult (id) ON DELETE CASCADE,
  CONSTRAINT fk_mp_medication  FOREIGN KEY (id_medication)  REFERENCES public.medication_catalog (id) ON DELETE RESTRICT,
  CONSTRAINT fk_mp_user        FOREIGN KEY (prescribed_by)   REFERENCES public.users (id) ON DELETE SET NULL
);

CREATE INDEX IF NOT EXISTS idx_medpresc_older_adult ON public.medication_prescriptions (id_older_adult);
CREATE INDEX IF NOT EXISTS idx_medpresc_medication ON public.medication_prescriptions (id_medication);
CREATE INDEX IF NOT EXISTS idx_medpresc_status ON public.medication_prescriptions (status);
CREATE INDEX IF NOT EXISTS idx_medpresc_start_date ON public.medication_prescriptions (start_date);

DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_trigger
    WHERE tgname = 'trg_medication_prescriptions_updated_at'
      AND tgrelid = 'public.medication_prescriptions'::regclass
      AND NOT tgisinternal
  ) THEN
    CREATE TRIGGER trg_medication_prescriptions_updated_at
      BEFORE UPDATE ON public.medication_prescriptions
      FOR EACH ROW EXECUTE FUNCTION public.set_updated_at();
  END IF;
END;
$$;

-- -----------------------------------------------------------------------------
-- 6. Kardex / Registro de Administración de Medicamentos (MAR en health_nursing)
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.medication_administrations (
  id                 INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_prescription    INTEGER NOT NULL,
  id_older_adult     INTEGER NOT NULL,
  scheduled_time     TIMESTAMPTZ NOT NULL,
  administered_time  TIMESTAMPTZ,
  status             e_administration_status NOT NULL DEFAULT 'scheduled',
  dose_given         VARCHAR(100),
  administered_by    INTEGER,
  omission_reason    TEXT,
  observations       TEXT,
  created_at         TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_ma_prescription FOREIGN KEY (id_prescription) REFERENCES public.medication_prescriptions (id) ON DELETE CASCADE,
  CONSTRAINT fk_ma_older_adult  FOREIGN KEY (id_older_adult)  REFERENCES public.older_adult (id) ON DELETE CASCADE,
  CONSTRAINT fk_ma_user         FOREIGN KEY (administered_by) REFERENCES public.users (id) ON DELETE SET NULL
);

CREATE INDEX IF NOT EXISTS idx_medadmin_prescription ON public.medication_administrations (id_prescription);
CREATE INDEX IF NOT EXISTS idx_medadmin_older_adult ON public.medication_administrations (id_older_adult);
CREATE INDEX IF NOT EXISTS idx_medadmin_scheduled_time ON public.medication_administrations (scheduled_time);
CREATE INDEX IF NOT EXISTS idx_medadmin_status ON public.medication_administrations (status);

-- -----------------------------------------------------------------------------
-- 7. Historial Completo de Inmunizaciones (health_vaccination)
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.patient_vaccinations (
  id                 INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_older_adult     INTEGER NOT NULL,
  id_vaccine         INTEGER,
  custom_vaccine_name VARCHAR(150),
  dose               e_vaccine_dose NOT NULL DEFAULT 'single',
  application_date   DATE NOT NULL,
  lot_number         VARCHAR(60),
  expiration_date    DATE,
  applied_by         VARCHAR(150),
  adverse_reactions  TEXT,
  next_booster_date  DATE,
  observations       TEXT,
  created_at         TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_pv_older_adult FOREIGN KEY (id_older_adult) REFERENCES public.older_adult (id) ON DELETE CASCADE,
  CONSTRAINT fk_pv_vaccine     FOREIGN KEY (id_vaccine)     REFERENCES public.vaccines (id) ON DELETE RESTRICT
);

CREATE INDEX IF NOT EXISTS idx_patvacc_older_adult ON public.patient_vaccinations (id_older_adult);
CREATE INDEX IF NOT EXISTS idx_patvacc_vaccine ON public.patient_vaccinations (id_vaccine);
CREATE INDEX IF NOT EXISTS idx_patvacc_app_date ON public.patient_vaccinations (application_date);

