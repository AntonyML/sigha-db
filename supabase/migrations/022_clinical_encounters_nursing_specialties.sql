-- -----------------------------------------------------------------------------
-- 1. Tipos ENUM para encuentros, rondas y escalas geriátricas
-- -----------------------------------------------------------------------------
DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_type WHERE typname = 'e_encounter_class') THEN
    CREATE TYPE e_encounter_class AS ENUM ('ambulatory', 'inpatient', 'emergency', 'home_care');
  END IF;

  IF NOT EXISTS (SELECT 1 FROM pg_type WHERE typname = 'e_encounter_status') THEN
    CREATE TYPE e_encounter_status AS ENUM ('scheduled', 'in_progress', 'completed', 'cancelled');
  END IF;

  IF NOT EXISTS (SELECT 1 FROM pg_type WHERE typname = 'e_encounter_type') THEN
    CREATE TYPE e_encounter_type AS ENUM ('nursing', 'medical', 'physiotherapy', 'psychology', 'social_work', 'specialized');
  END IF;

  IF NOT EXISTS (SELECT 1 FROM pg_type WHERE typname = 'e_nursing_shift') THEN
    CREATE TYPE e_nursing_shift AS ENUM ('morning', 'afternoon', 'night');
  END IF;

  IF NOT EXISTS (SELECT 1 FROM pg_type WHERE typname = 'e_barthel_level') THEN
    CREATE TYPE e_barthel_level AS ENUM ('total_dependence', 'severe_dependence', 'moderate_dependence', 'mild_dependence', 'independent');
  END IF;

  IF NOT EXISTS (SELECT 1 FROM pg_type WHERE typname = 'e_gds_level') THEN
    CREATE TYPE e_gds_level AS ENUM ('normal', 'mild_depression', 'moderate_depression', 'severe_depression');
  END IF;

  IF NOT EXISTS (SELECT 1 FROM pg_type WHERE typname = 'e_pfeiffer_level') THEN
    CREATE TYPE e_pfeiffer_level AS ENUM ('intact', 'mild_impairment', 'moderate_impairment', 'severe_impairment');
  END IF;

  IF NOT EXISTS (SELECT 1 FROM pg_type WHERE typname = 'e_apgar_level') THEN
    CREATE TYPE e_apgar_level AS ENUM ('highly_functional', 'mild_dysfunction', 'severe_dysfunction');
  END IF;
END $$;

-- -----------------------------------------------------------------------------
-- 2. Habitaciones y asignación de camas (GNU Health: health_inpatient)
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS facility_rooms (
  id              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  room_number     VARCHAR(20)  NOT NULL UNIQUE,
  name            VARCHAR(100) NOT NULL,
  floor_wing      VARCHAR(50),
  capacity        INTEGER      NOT NULL DEFAULT 1 CHECK (capacity >= 1),
  is_active       BOOLEAN      NOT NULL DEFAULT TRUE,
  created_at      TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_rooms_number ON facility_rooms (room_number);
CREATE INDEX IF NOT EXISTS idx_rooms_active ON facility_rooms (is_active);

CREATE TABLE IF NOT EXISTS patient_bed_assignments (
  id              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_older_adult  INTEGER      NOT NULL REFERENCES older_adult (id) ON DELETE CASCADE,
  id_room         INTEGER      NOT NULL REFERENCES facility_rooms (id) ON DELETE RESTRICT,
  bed_label       VARCHAR(20)  NOT NULL DEFAULT 'Cama 1',
  assigned_at     TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
  discharged_at   TIMESTAMPTZ,
  is_current      BOOLEAN      NOT NULL DEFAULT TRUE,
  notes           TEXT,
  created_at      TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_bed_assign_patient  ON patient_bed_assignments (id_older_adult);
CREATE INDEX IF NOT EXISTS idx_bed_assign_room     ON patient_bed_assignments (id_room);
CREATE INDEX IF NOT EXISTS idx_bed_assign_current  ON patient_bed_assignments (is_current);

-- -----------------------------------------------------------------------------
-- 3. Encuentros clínicos estructurados (SOAP) y ciclo de vida
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS clinical_encounters (
  id              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_older_adult  INTEGER            NOT NULL REFERENCES older_adult (id) ON DELETE CASCADE,
  id_professional INTEGER            REFERENCES users (id) ON DELETE SET NULL,
  encounter_class e_encounter_class  NOT NULL DEFAULT 'inpatient',
  encounter_type  e_encounter_type   NOT NULL DEFAULT 'nursing',
  status          e_encounter_status NOT NULL DEFAULT 'scheduled',
  start_time      TIMESTAMPTZ        NOT NULL DEFAULT CURRENT_TIMESTAMP,
  end_time        TIMESTAMPTZ,
  chief_complaint TEXT,
  so_subjective   TEXT,
  so_objective    TEXT,
  so_assessment   TEXT,
  so_plan         TEXT,
  is_signed       BOOLEAN            NOT NULL DEFAULT FALSE,
  signed_at       TIMESTAMPTZ,
  signed_by       INTEGER            REFERENCES users (id) ON DELETE SET NULL,
  id_appointment  INTEGER            REFERENCES specialized_appointment (id) ON DELETE SET NULL,
  created_at      TIMESTAMPTZ        NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at      TIMESTAMPTZ        NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_encounters_patient   ON clinical_encounters (id_older_adult);
CREATE INDEX IF NOT EXISTS idx_encounters_prof      ON clinical_encounters (id_professional);
CREATE INDEX IF NOT EXISTS idx_encounters_status    ON clinical_encounters (status);
CREATE INDEX IF NOT EXISTS idx_encounters_type      ON clinical_encounters (encounter_type);
CREATE INDEX IF NOT EXISTS idx_encounters_start     ON clinical_encounters (start_time);
CREATE INDEX IF NOT EXISTS idx_encounters_signed    ON clinical_encounters (is_signed);

DROP TRIGGER IF EXISTS trg_clinical_encounters_updated_at ON clinical_encounters;
CREATE TRIGGER trg_clinical_encounters_updated_at
  BEFORE UPDATE ON clinical_encounters
  FOR EACH ROW
  EXECUTE FUNCTION set_updated_at();

-- -----------------------------------------------------------------------------
-- 4. Signos vitales numéricos y observaciones clínicas (HL7 FHIR Observation)
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS clinical_vital_signs (
  id                INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_older_adult    INTEGER       NOT NULL REFERENCES older_adult (id) ON DELETE CASCADE,
  id_encounter      INTEGER       REFERENCES clinical_encounters (id) ON DELETE SET NULL,
  systolic_bp       INTEGER       CHECK (systolic_bp BETWEEN 40 AND 300),
  diastolic_bp      INTEGER       CHECK (diastolic_bp BETWEEN 20 AND 200),
  heart_rate        INTEGER       CHECK (heart_rate BETWEEN 20 AND 250),
  respiratory_rate  INTEGER       CHECK (respiratory_rate BETWEEN 5 AND 60),
  temperature       NUMERIC(4,1)  CHECK (temperature BETWEEN 30.0 AND 45.0),
  spo2              INTEGER       CHECK (spo2 BETWEEN 50 AND 100),
  glycemia          NUMERIC(5,1)  CHECK (glycemia BETWEEN 10.0 AND 800.0),
  pain_eva          SMALLINT      CHECK (pain_eva BETWEEN 0 AND 10),
  weight_kg         NUMERIC(5,2)  CHECK (weight_kg > 0 AND weight_kg < 400),
  height_cm         NUMERIC(5,2)  CHECK (height_cm > 0 AND height_cm < 250),
  notes             TEXT,
  recorded_at       TIMESTAMPTZ   NOT NULL DEFAULT CURRENT_TIMESTAMP,
  recorded_by       INTEGER       REFERENCES users (id) ON DELETE SET NULL
);

CREATE INDEX IF NOT EXISTS idx_vitals_patient  ON clinical_vital_signs (id_older_adult);
CREATE INDEX IF NOT EXISTS idx_vitals_enc      ON clinical_vital_signs (id_encounter);
CREATE INDEX IF NOT EXISTS idx_vitals_date     ON clinical_vital_signs (recorded_at);

-- -----------------------------------------------------------------------------
-- 5. Rondas de enfermería por turno de sala
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS nursing_rounds (
  id                  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_older_adult      INTEGER         NOT NULL REFERENCES older_adult (id) ON DELETE CASCADE,
  id_staff            INTEGER         NOT NULL REFERENCES users (id) ON DELETE CASCADE,
  round_date          DATE            NOT NULL DEFAULT CURRENT_DATE,
  shift               e_nursing_shift NOT NULL DEFAULT 'morning',
  id_vital_signs      INTEGER         REFERENCES clinical_vital_signs (id) ON DELETE SET NULL,
  general_condition   TEXT,
  skin_integrity      TEXT,
  nutrition_hydration TEXT,
  elimination         TEXT,
  mobility_comfort    TEXT,
  fall_risk           VARCHAR(20)     DEFAULT 'medium',
  notes               TEXT,
  created_at          TIMESTAMPTZ     NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_nursing_rounds_patient ON nursing_rounds (id_older_adult);
CREATE INDEX IF NOT EXISTS idx_nursing_rounds_staff   ON nursing_rounds (id_staff);
CREATE INDEX IF NOT EXISTS idx_nursing_rounds_date    ON nursing_rounds (round_date, shift);

-- -----------------------------------------------------------------------------
-- 6. Inmutabilidad y adendas a notas clínicas (GNU Health: health_crypto)
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS clinical_note_addendums (
  id                  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_encounter        INTEGER     NOT NULL REFERENCES clinical_encounters (id) ON DELETE CASCADE,
  author_id           INTEGER     NOT NULL REFERENCES users (id) ON DELETE RESTRICT,
  addendum_text       TEXT        NOT NULL,
  reason_for_addendum TEXT        NOT NULL,
  signed_at           TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  created_at          TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_addendums_enc    ON clinical_note_addendums (id_encounter);
CREATE INDEX IF NOT EXISTS idx_addendums_author ON clinical_note_addendums (author_id);

-- -----------------------------------------------------------------------------
-- 7. Evaluaciones geriátricas: Fisioterapia (Escala Barthel 0-100)
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS physiotherapy_evaluations (
  id                    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_older_adult        INTEGER         NOT NULL REFERENCES older_adult (id) ON DELETE CASCADE,
  id_encounter          INTEGER         REFERENCES clinical_encounters (id) ON DELETE SET NULL,
  evaluator_id          INTEGER         NOT NULL REFERENCES users (id) ON DELETE CASCADE,
  evaluation_date       TIMESTAMPTZ     NOT NULL DEFAULT CURRENT_TIMESTAMP,
  barthel_feeding       INTEGER         NOT NULL DEFAULT 10 CHECK (barthel_feeding IN (0, 5, 10)),
  barthel_bathing       INTEGER         NOT NULL DEFAULT 5  CHECK (barthel_bathing IN (0, 5)),
  barthel_grooming      INTEGER         NOT NULL DEFAULT 5  CHECK (barthel_grooming IN (0, 5)),
  barthel_dressing      INTEGER         NOT NULL DEFAULT 10 CHECK (barthel_dressing IN (0, 5, 10)),
  barthel_bowels        INTEGER         NOT NULL DEFAULT 10 CHECK (barthel_bowels IN (0, 5, 10)),
  barthel_bladder       INTEGER         NOT NULL DEFAULT 10 CHECK (barthel_bladder IN (0, 5, 10)),
  barthel_toilet_use    INTEGER         NOT NULL DEFAULT 10 CHECK (barthel_toilet_use IN (0, 5, 10)),
  barthel_transfers     INTEGER         NOT NULL DEFAULT 15 CHECK (barthel_transfers IN (0, 5, 10, 15)),
  barthel_mobility      INTEGER         NOT NULL DEFAULT 15 CHECK (barthel_mobility IN (0, 5, 10, 15)),
  barthel_stairs        INTEGER         NOT NULL DEFAULT 10 CHECK (barthel_stairs IN (0, 5, 10)),
  barthel_total_score   INTEGER         NOT NULL CHECK (barthel_total_score BETWEEN 0 AND 100),
  dependence_level      e_barthel_level NOT NULL,
  tinetti_gait_score    INTEGER         CHECK (tinetti_gait_score BETWEEN 0 AND 12),
  tinetti_balance_score INTEGER         CHECK (tinetti_balance_score BETWEEN 0 AND 16),
  rehabilitation_goals  TEXT,
  treatment_plan        TEXT,
  notes                 TEXT,
  created_at            TIMESTAMPTZ     NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_physio_eval_patient ON physiotherapy_evaluations (id_older_adult);
CREATE INDEX IF NOT EXISTS idx_physio_eval_enc     ON physiotherapy_evaluations (id_encounter);
CREATE INDEX IF NOT EXISTS idx_physio_eval_date    ON physiotherapy_evaluations (evaluation_date);

-- -----------------------------------------------------------------------------
-- 8. Evaluaciones geriátricas: Psicología (Yesavage GDS 0-15 y Pfeiffer 0-10)
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS psychology_evaluations (
  id                      INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_older_adult          INTEGER          NOT NULL REFERENCES older_adult (id) ON DELETE CASCADE,
  id_encounter            INTEGER          REFERENCES clinical_encounters (id) ON DELETE SET NULL,
  evaluator_id            INTEGER          NOT NULL REFERENCES users (id) ON DELETE CASCADE,
  evaluation_date         TIMESTAMPTZ      NOT NULL DEFAULT CURRENT_TIMESTAMP,
  yesavage_gds_score      INTEGER          CHECK (yesavage_gds_score BETWEEN 0 AND 15),
  depression_severity     e_gds_level,
  pfeiffer_errors_score   INTEGER          CHECK (pfeiffer_errors_score BETWEEN 0 AND 10),
  cognitive_impairment    e_pfeiffer_level,
  emotional_state         TEXT,
  behavioral_observations TEXT,
  intervention_plan       TEXT,
  notes                   TEXT,
  created_at              TIMESTAMPTZ      NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_psy_eval_patient ON psychology_evaluations (id_older_adult);
CREATE INDEX IF NOT EXISTS idx_psy_eval_enc     ON psychology_evaluations (id_encounter);
CREATE INDEX IF NOT EXISTS idx_psy_eval_date    ON psychology_evaluations (evaluation_date);

-- -----------------------------------------------------------------------------
-- 9. Evaluaciones geriátricas: Trabajo Social (APGAR familiar 0-10)
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS social_work_evaluations (
  id                            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_older_adult                INTEGER       NOT NULL REFERENCES older_adult (id) ON DELETE CASCADE,
  id_encounter                  INTEGER       REFERENCES clinical_encounters (id) ON DELETE SET NULL,
  evaluator_id                  INTEGER       NOT NULL REFERENCES users (id) ON DELETE CASCADE,
  evaluation_date               TIMESTAMPTZ   NOT NULL DEFAULT CURRENT_TIMESTAMP,
  apgar_adaptation              INTEGER       NOT NULL DEFAULT 2 CHECK (apgar_adaptation BETWEEN 0 AND 2),
  apgar_partnership             INTEGER       NOT NULL DEFAULT 2 CHECK (apgar_partnership BETWEEN 0 AND 2),
  apgar_growth                  INTEGER       NOT NULL DEFAULT 2 CHECK (apgar_growth BETWEEN 0 AND 2),
  apgar_affection               INTEGER       NOT NULL DEFAULT 2 CHECK (apgar_affection BETWEEN 0 AND 2),
  apgar_resolve                 INTEGER       NOT NULL DEFAULT 2 CHECK (apgar_resolve BETWEEN 0 AND 2),
  apgar_total_score             INTEGER       NOT NULL CHECK (apgar_total_score BETWEEN 0 AND 10),
  family_functioning            e_apgar_level NOT NULL,
  family_support_network        TEXT,
  socioeconomic_assessment      TEXT,
  institutional_recommendations TEXT,
  notes                         TEXT,
  created_at                    TIMESTAMPTZ   NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_sw_eval_patient ON social_work_evaluations (id_older_adult);
CREATE INDEX IF NOT EXISTS idx_sw_eval_enc     ON social_work_evaluations (id_encounter);
CREATE INDEX IF NOT EXISTS idx_sw_eval_date    ON social_work_evaluations (evaluation_date);

