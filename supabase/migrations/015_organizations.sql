-- =============================================================================
-- 015_organizations.sql
-- Multi-tenant organizations and user memberships.
-- Seeds the legacy ASOPOGUA organization and makes each existing user a primary
-- member. Safe to re-run.
-- =============================================================================

CREATE TABLE IF NOT EXISTS public.organizations (
  id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name       VARCHAR(200) NOT NULL,
  slug       CITEXT NOT NULL UNIQUE,
  logo_url   TEXT,
  is_active  BOOLEAN DEFAULT TRUE,
  created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS public.organization_members (
  user_id         INTEGER NOT NULL,
  organization_id INTEGER NOT NULL,
  is_primary      BOOLEAN DEFAULT FALSE,
  CONSTRAINT fk_organization_members_user
    FOREIGN KEY (user_id) REFERENCES public.users (id),
  CONSTRAINT fk_organization_members_organization
    FOREIGN KEY (organization_id) REFERENCES public.organizations (id),
  CONSTRAINT uq_organization_members_user_organization
    UNIQUE (user_id, organization_id)
);

CREATE INDEX IF NOT EXISTS idx_organization_members_user_id
  ON public.organization_members (user_id);

CREATE INDEX IF NOT EXISTS idx_organization_members_organization_id
  ON public.organization_members (organization_id);

DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1
    FROM pg_trigger
    WHERE tgname = 'trg_organizations_updated_at'
      AND tgrelid = 'public.organizations'::regclass
      AND NOT tgisinternal
  ) THEN
    EXECUTE 'CREATE TRIGGER trg_organizations_updated_at
      BEFORE UPDATE ON public.organizations
      FOR EACH ROW EXECUTE FUNCTION public.set_updated_at()';
  END IF;
END;
$$;

INSERT INTO public.organizations (name, slug)
VALUES ('ASOPOGUA', 'asopogua')
ON CONFLICT DO NOTHING;

INSERT INTO public.organization_members (user_id, organization_id, is_primary)
SELECT u.id, o.id, TRUE
FROM public.users AS u
CROSS JOIN public.organizations AS o
WHERE o.slug = 'asopogua'
ON CONFLICT (user_id, organization_id) DO NOTHING;
