-- -----------------------------------------------------------------------------
-- older_adult_family
-- -----------------------------------------------------------------------------
CREATE TABLE older_adult_family (
  id                INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  pf_identification VARCHAR(20) NOT NULL,
  pf_name           VARCHAR(50) NOT NULL,
  pf_f_last_name    VARCHAR(50) NOT NULL,
  pf_s_last_name    VARCHAR(50) NOT NULL,
  pf_phone_number   VARCHAR(20),
  pf_email          VARCHAR(256),
  pf_kinship        e_pf_kinship NOT NULL DEFAULT 'not specified',
  pf_is_active      BOOLEAN     NOT NULL DEFAULT TRUE,
  create_at         TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_adult_family_identification ON older_adult_family (pf_identification);
CREATE INDEX idx_adult_family_email          ON older_adult_family (pf_email);
CREATE INDEX idx_adult_family_kinship        ON older_adult_family (pf_kinship);

-- -----------------------------------------------------------------------------
-- older_adult (residents)
-- -----------------------------------------------------------------------------
CREATE TABLE older_adult (
  id                  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  oa_identification   VARCHAR(20) NOT NULL UNIQUE,
  oa_name             VARCHAR(50) NOT NULL,
  oa_f_last_name      VARCHAR(50) NOT NULL,
  oa_s_last_name      VARCHAR(50),
  oa_birthdate        DATE,
  oa_marital_status   e_oa_marital_status   NOT NULL DEFAULT 'not specified',
  oa_dwelling         TEXT,
  oa_years_schooling  e_oa_years_schooling  NOT NULL DEFAULT 'not specified',
  oa_previous_work    VARCHAR(300) NOT NULL,
  oa_is_retired       BOOLEAN      NOT NULL DEFAULT FALSE,
  oa_has_pension      BOOLEAN      NOT NULL DEFAULT FALSE,
  oa_other            BOOLEAN      NOT NULL DEFAULT FALSE,
  oa_other_description VARCHAR(300),
  oa_area_of_origin   VARCHAR(300),
  oa_children_count   SMALLINT     NOT NULL DEFAULT 0,
  oa_status           e_oa_status  NOT NULL DEFAULT 'alive',
  oa_death_date       DATE,
  oa_economic_income  NUMERIC(10,2),
  oa_phone_numner     VARCHAR(20),
  oa_email            VARCHAR(256),
  oa_profile_photo_url VARCHAR(255),
  oa_gender           e_oa_gender  NOT NULL DEFAULT 'not specified',
  oa_blood_type       e_oa_blood_type NOT NULL DEFAULT 'UNKNOWN',
  oa_is_active        BOOLEAN      NOT NULL DEFAULT TRUE,
  create_at           TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
  id_program          INTEGER,
  id_family           INTEGER,
  CONSTRAINT fk_oa_program FOREIGN KEY (id_program) REFERENCES programs (id)             ON DELETE SET NULL,
  CONSTRAINT fk_oa_family  FOREIGN KEY (id_family)  REFERENCES older_adult_family (id)   ON DELETE SET NULL
);

CREATE INDEX idx_olderadult_identification ON older_adult (oa_identification);
CREATE INDEX idx_olderadult_name           ON older_adult (oa_name);
CREATE INDEX idx_olderadult_f_lastname     ON older_adult (oa_f_last_name);
CREATE INDEX idx_olderadult_email          ON older_adult (oa_email);
CREATE INDEX idx_olderadult_birthdate      ON older_adult (oa_birthdate);
CREATE INDEX idx_olderadult_status         ON older_adult (oa_status);
CREATE INDEX idx_olderadult_active         ON older_adult (oa_is_active);

-- -----------------------------------------------------------------------------
-- older_adult_subprogram (M:N)
-- -----------------------------------------------------------------------------
CREATE TABLE older_adult_subprogram (
  id_older_adult INTEGER NOT NULL,
  id_sub_program INTEGER NOT NULL,
  CONSTRAINT pk_oasub PRIMARY KEY (id_older_adult, id_sub_program),
  CONSTRAINT fk_oasub_adult  FOREIGN KEY (id_older_adult) REFERENCES older_adult  (id) ON DELETE CASCADE,
  CONSTRAINT fk_oasub_subpg  FOREIGN KEY (id_sub_program) REFERENCES sub_programs (id) ON DELETE CASCADE
);

-- -----------------------------------------------------------------------------
-- emergency_contacts
-- -----------------------------------------------------------------------------
CREATE TABLE emergency_contacts (
  id              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  en_phone_number VARCHAR(20) NOT NULL,
  en_contact_name VARCHAR(100),
  create_at       TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  id_older_adult  INTEGER,
  CONSTRAINT fk_ec_oa FOREIGN KEY (id_older_adult) REFERENCES older_adult (id) ON DELETE CASCADE
);

CREATE INDEX idx_emergency_number   ON emergency_contacts (en_phone_number);
CREATE INDEX idx_emergency_older    ON emergency_contacts (id_older_adult);

-- -----------------------------------------------------------------------------
-- older_adult_updates
-- -----------------------------------------------------------------------------
CREATE TABLE older_adult_updates (
  id                INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  oau_field_changed VARCHAR(100) NOT NULL,
  oau_old_value     TEXT,
  oau_new_value     TEXT,
  changed_at        TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
  id_older_adult    INTEGER NOT NULL,
  changed_by        INTEGER NOT NULL,
  CONSTRAINT fk_oau_adult FOREIGN KEY (id_older_adult) REFERENCES older_adult (id),
  CONSTRAINT fk_oau_user  FOREIGN KEY (changed_by)     REFERENCES users (id)
);

CREATE INDEX idx_adultupdates_adult ON older_adult_updates (id_older_adult);
CREATE INDEX idx_adultupdates_field ON older_adult_updates (oau_field_changed);

