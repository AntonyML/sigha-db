-- -----------------------------------------------------------------------------
-- clinical_history
-- -----------------------------------------------------------------------------
CREATE TABLE clinical_history (
  id                    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ch_frequent_falls      BOOLEAN     NOT NULL DEFAULT FALSE,
  ch_weight              NUMERIC(5,2),
  ch_height              NUMERIC(4,2),
  ch_imc                 NUMERIC(4,1),
  ch_blood_pressure      VARCHAR(7),
  ch_neoplasms           BOOLEAN     NOT NULL DEFAULT FALSE,
  ch_neoplasms_description VARCHAR(300),
  ch_observations       TEXT,
  ch_rcvg                e_clinical_rcvg NOT NULL DEFAULT 'UNKNOWN',
  ch_vision_problems     BOOLEAN     NOT NULL DEFAULT FALSE,
  ch_vision_hearing      BOOLEAN     NOT NULL DEFAULT FALSE,
  create_at              TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  id_older_adult         INTEGER,
  CONSTRAINT fk_ch_oa FOREIGN KEY (id_older_adult) REFERENCES older_adult (id)
);

CREATE INDEX idx_clinicalhistory_createat ON clinical_history (create_at);
CREATE INDEX idx_clinicalhistory_oa        ON clinical_history (id_older_adult);

-- -----------------------------------------------------------------------------
-- clinical_history_and_conditions (M:N)
-- -----------------------------------------------------------------------------
CREATE TABLE clinical_history_and_conditions (
  id_c_condition INTEGER NOT NULL,
  id_c_history   INTEGER NOT NULL,
  CONSTRAINT pk_chc PRIMARY KEY (id_c_condition, id_c_history),
  CONSTRAINT fk_chc_cond FOREIGN KEY (id_c_condition) REFERENCES clinical_conditions (id) ON DELETE CASCADE,
  CONSTRAINT fk_chc_hist FOREIGN KEY (id_c_history)   REFERENCES clinical_history   (id) ON DELETE CASCADE
);

-- -----------------------------------------------------------------------------
-- vaccines_and_clinical_history (M:N)
-- -----------------------------------------------------------------------------
CREATE TABLE vaccines_and_clinical_history (
  id_vaccine   INTEGER NOT NULL,
  id_c_history INTEGER NOT NULL,
  CONSTRAINT pk_vch PRIMARY KEY (id_vaccine, id_c_history),
  CONSTRAINT fk_vch_vac  FOREIGN KEY (id_vaccine)   REFERENCES vaccines         (id) ON DELETE CASCADE,
  CONSTRAINT fk_vch_hist FOREIGN KEY (id_c_history) REFERENCES clinical_history (id) ON DELETE CASCADE
);

-- -----------------------------------------------------------------------------
-- clinical_medication
-- -----------------------------------------------------------------------------
CREATE TABLE clinical_medication (
  id                  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  m_medication        VARCHAR(500) NOT NULL,
  m_dosage            VARCHAR(200) NOT NULL,
  m_treatment_type    e_medication_treatment_type NOT NULL DEFAULT 'other',
  id_clinical_history INTEGER,
  CONSTRAINT fk_cm_ch FOREIGN KEY (id_clinical_history) REFERENCES clinical_history (id) ON DELETE CASCADE
);

CREATE INDEX idx_clinicalmedication_medication ON clinical_medication (m_medication);

