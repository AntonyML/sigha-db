-- -----------------------------------------------------------------------------
-- 1. Tipos ENUM para Estilo de Vida y Hábitos
-- -----------------------------------------------------------------------------
DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_type WHERE typname = 'e_diet_type') THEN
    CREATE TYPE e_diet_type AS ENUM (
      'general',
      'soft',
      'pureed',
      'diabetic',
      'low_sodium',
      'renal',
      'enteral',
      'hypocaloric',
      'other'
    );
  END IF;

  IF NOT EXISTS (SELECT 1 FROM pg_type WHERE typname = 'e_appetite_level') THEN
    CREATE TYPE e_appetite_level AS ENUM (
      'normal',
      'reduced',
      'increased',
      'anorexic',
      'variable'
    );
  END IF;

  IF NOT EXISTS (SELECT 1 FROM pg_type WHERE typname = 'e_sleep_quality') THEN
    CREATE TYPE e_sleep_quality AS ENUM (
      'good',
      'fair',
      'insomnia',
      'fragmented',
      'somnolence'
    );
  END IF;

  IF NOT EXISTS (SELECT 1 FROM pg_type WHERE typname = 'e_physical_activity_level') THEN
    CREATE TYPE e_physical_activity_level AS ENUM (
      'sedentary',
      'light_assisted',
      'moderate',
      'active'
    );
  END IF;

  IF NOT EXISTS (SELECT 1 FROM pg_type WHERE typname = 'e_smoking_status') THEN
    CREATE TYPE e_smoking_status AS ENUM (
      'never',
      'former',
      'active_light',
      'active_heavy',
      'passive'
    );
  END IF;

  IF NOT EXISTS (SELECT 1 FROM pg_type WHERE typname = 'e_alcohol_status') THEN
    CREATE TYPE e_alcohol_status AS ENUM (
      'never',
      'former',
      'occasional_social',
      'risk_abuse'
    );
  END IF;
END $$;

-- -----------------------------------------------------------------------------
-- 2. Tabla de Evaluaciones de Estilo de Vida (patient_lifestyle_assessments)
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS patient_lifestyle_assessments (
  id                          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_older_adult              INTEGER NOT NULL REFERENCES older_adult (id) ON DELETE CASCADE,
  assessed_at                 TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  assessed_by                 INTEGER REFERENCES users (id) ON DELETE SET NULL,

  -- Nutrición y Dieta
  diet_type                   e_diet_type NOT NULL DEFAULT 'general',
  diet_consistency            VARCHAR(50) NOT NULL DEFAULT 'regular',
  diet_allergies_intolerances TEXT,
  meals_per_day               INTEGER NOT NULL DEFAULT 4 CHECK (meals_per_day >= 1 AND meals_per_day <= 10),
  appetite                    e_appetite_level NOT NULL DEFAULT 'normal',
  daily_fluid_intake_ml       INTEGER NOT NULL DEFAULT 1500 CHECK (daily_fluid_intake_ml >= 0),
  requires_fluid_thickener    BOOLEAN NOT NULL DEFAULT FALSE,
  diet_notes                  TEXT,

  -- Sueño y Descanso
  sleep_hours_per_night       NUMERIC(3, 1) NOT NULL DEFAULT 7.0 CHECK (sleep_hours_per_night >= 0 AND sleep_hours_per_night <= 24),
  sleep_quality               e_sleep_quality NOT NULL DEFAULT 'good',
  sleep_medication_required   BOOLEAN NOT NULL DEFAULT FALSE,
  sleep_notes                 TEXT,

  -- Actividad Física y Movilidad
  physical_activity_level     e_physical_activity_level NOT NULL DEFAULT 'sedentary',
  daily_walking_minutes       INTEGER NOT NULL DEFAULT 15 CHECK (daily_walking_minutes >= 0),
  mobility_assistance_required BOOLEAN NOT NULL DEFAULT FALSE,
  physical_activity_notes     TEXT,

  -- Hábitos Tóxicos / Factores de Riesgo
  smoking_status              e_smoking_status NOT NULL DEFAULT 'never',
  smoking_packs_year          NUMERIC(4, 1) NOT NULL DEFAULT 0.0 CHECK (smoking_packs_year >= 0),
  alcohol_status              e_alcohol_status NOT NULL DEFAULT 'never',

  -- Conclusiones y Plan
  lifestyle_summary           TEXT,
  created_at                  TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at                  TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_lifestyle_older_adult
  ON patient_lifestyle_assessments(id_older_adult);

CREATE INDEX IF NOT EXISTS idx_lifestyle_assessed_at
  ON patient_lifestyle_assessments(assessed_at DESC);

-- Trigger de updated_at
CREATE OR REPLACE FUNCTION trg_set_timestamp_lifestyle()
RETURNS TRIGGER AS $$
BEGIN
  NEW.updated_at = CURRENT_TIMESTAMP;
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS set_timestamp_lifestyle ON patient_lifestyle_assessments;
CREATE TRIGGER set_timestamp_lifestyle
  BEFORE UPDATE ON patient_lifestyle_assessments
  FOR EACH ROW
  EXECUTE FUNCTION trg_set_timestamp_lifestyle();

COMMENT ON TABLE patient_lifestyle_assessments IS
  'Evaluaciones periódicas de hábitos de vida, nutrición, hidratación, descanso y actividad física según estándar GNU Health health_lifestyle';
