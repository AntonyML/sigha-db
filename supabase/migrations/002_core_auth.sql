-- -----------------------------------------------------------------------------
-- roles
-- -----------------------------------------------------------------------------
CREATE TABLE roles (
  id    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  r_name e_user_role NOT NULL DEFAULT 'not specified'
);

CREATE INDEX idx_role_name ON roles (r_name);

-- -----------------------------------------------------------------------------
-- users (staff / system accounts)
-- -----------------------------------------------------------------------------
CREATE TABLE users (
  id               INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  u_identification VARCHAR(20)  NOT NULL UNIQUE,
  u_name           VARCHAR(50)  NOT NULL,
  u_f_last_name    VARCHAR(50)  NOT NULL,
  u_s_last_name    VARCHAR(50),
  u_email          VARCHAR(256) NOT NULL UNIQUE,
  u_email_verified BOOLEAN      NOT NULL DEFAULT FALSE,
  u_password       VARCHAR(255) NOT NULL,
  u_is_active      BOOLEAN      NOT NULL DEFAULT TRUE,
  create_at        TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
  role_id          INTEGER,
  CONSTRAINT fk_users_role FOREIGN KEY (role_id) REFERENCES roles (id) ON DELETE SET NULL
);

CREATE INDEX idx_user_email         ON users (u_email);
CREATE INDEX idx_user_identification ON users (u_identification);
CREATE INDEX idx_user_role          ON users (role_id);
CREATE INDEX idx_user_active        ON users (u_is_active);

-- -----------------------------------------------------------------------------
-- user_two_factor (TOTP)
-- -----------------------------------------------------------------------------
CREATE TABLE user_two_factor (
  id               INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id          INTEGER NOT NULL,
  tfa_secret       VARCHAR(255) NOT NULL,
  tfa_enabled      BOOLEAN      NOT NULL DEFAULT FALSE,
  tfa_backup_codes TEXT,                              -- JSON array of (hashed) codes
  tfa_last_used    TIMESTAMPTZ,
  created_at       TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at       TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_tfa_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE,
  CONSTRAINT uq_tfa_user UNIQUE (user_id)
);

-- -----------------------------------------------------------------------------
-- user_sessions (JWT sessions)
-- -----------------------------------------------------------------------------
CREATE TABLE user_sessions (
  id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id       INTEGER NOT NULL,
  session_token VARCHAR(500) NOT NULL,
  refresh_token VARCHAR(500),
  ip_address    VARCHAR(45),
  user_agent    TEXT,
  is_active     BOOLEAN     NOT NULL DEFAULT TRUE,
  expires_at    TIMESTAMPTZ NOT NULL,
  created_at    TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  last_activity TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_session_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE
);

CREATE INDEX idx_user_sessions        ON user_sessions (user_id, is_active);
CREATE INDEX idx_session_token        ON user_sessions (session_token);
CREATE INDEX idx_expires_at           ON user_sessions (expires_at);

-- -----------------------------------------------------------------------------
-- login_attempts (security audit)
-- -----------------------------------------------------------------------------
CREATE TABLE login_attempts (
  id                INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id           INTEGER,
  email             VARCHAR(256) NOT NULL,
  ip_address        VARCHAR(45),
  attempt_successful BOOLEAN     NOT NULL DEFAULT FALSE,
  failure_reason    VARCHAR(100),
  attempted_at      TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_attempt_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE SET NULL
);

CREATE INDEX idx_login_attempts ON login_attempts (email, attempted_at);
CREATE INDEX idx_ip_attempts    ON login_attempts (ip_address, attempted_at);

-- -----------------------------------------------------------------------------
-- password_reset_tokens
-- -----------------------------------------------------------------------------
CREATE TABLE password_reset_tokens (
  id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id    INTEGER NOT NULL,
  token      VARCHAR(255) NOT NULL,
  expires_at TIMESTAMPTZ  NOT NULL,
  used       BOOLEAN      NOT NULL DEFAULT FALSE,
  used_at    TIMESTAMPTZ,
  created_at TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_pwreset_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE
);

CREATE INDEX idx_token    ON password_reset_tokens (token);
CREATE INDEX idx_expires  ON password_reset_tokens (expires_at, used);

-- -----------------------------------------------------------------------------
-- email_verification_tokens
-- -----------------------------------------------------------------------------
CREATE TABLE email_verification_tokens (
  id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id     INTEGER NOT NULL,
  token       VARCHAR(255) NOT NULL UNIQUE,
  expires_at  TIMESTAMPTZ NOT NULL,
  verified    BOOLEAN     NOT NULL DEFAULT FALSE,
  verified_at TIMESTAMPTZ,
  created_at  TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_evtoken_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE
);

CREATE INDEX idx_evtoken_token   ON email_verification_tokens (token);
CREATE INDEX idx_evtoken_expires ON email_verification_tokens (expires_at, verified);

-- -----------------------------------------------------------------------------
-- role_changes (history)
-- -----------------------------------------------------------------------------
CREATE TABLE role_changes (
  id           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  rc_old_role  VARCHAR(50),
  rc_new_role  VARCHAR(50),
  changed_at   TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  id_user      INTEGER NOT NULL,
  changed_by   INTEGER NOT NULL,
  CONSTRAINT fk_rolechange_user FOREIGN KEY (id_user)    REFERENCES users (id),
  CONSTRAINT fk_rolechange_by   FOREIGN KEY (changed_by) REFERENCES users (id)
);

CREATE INDEX idx_rolechanges_user      ON role_changes (id_user);
CREATE INDEX idx_rolechanges_changedby ON role_changes (changed_by);

