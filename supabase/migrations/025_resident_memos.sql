-- =============================================================================
-- 025_resident_memos.sql
-- Módulo de Bitácora y Derivaciones Interdepartamentales (Estilo Memos)
-- Hilo de notas, derivaciones interdepartamentales (@usuario / #rol),
-- control de visibilidad clínica (public / clinical / confidential),
-- y soporte para adjuntos y acuses de recibo / resolución.
-- Idempotente y re-ejecutable.
-- Run after 024.
-- =============================================================================

-- -----------------------------------------------------------------------------
-- 1. Tipos ENUM para el sistema de memos y derivaciones
-- -----------------------------------------------------------------------------
DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_type WHERE typname = 'e_memo_visibility') THEN
    CREATE TYPE e_memo_visibility AS ENUM (
      'public',        -- Visible por todo el staff con acceso al expediente
      'clinical',      -- Visible solo por áreas clínicas y de salud
      'confidential'   -- Visible solo por el autor y dirección médica
    );
  END IF;

  IF NOT EXISTS (SELECT 1 FROM pg_type WHERE typname = 'e_memo_status') THEN
    CREATE TYPE e_memo_status AS ENUM (
      'open',          -- Abierto / Pendiente de atención
      'in_progress',   -- En proceso / En revisión
      'resolved',      -- Resuelto / Completado
      'archived'       -- Archivado
    );
  END IF;

  IF NOT EXISTS (SELECT 1 FROM pg_type WHERE typname = 'e_memo_urgency') THEN
    CREATE TYPE e_memo_urgency AS ENUM (
      'routine',       -- Rutina (sin urgencia inmediata)
      'priority',      -- Prioritario (atención en jornada)
      'urgent'         -- Urgente (atención inmediata requerida)
    );
  END IF;

  IF NOT EXISTS (SELECT 1 FROM pg_type WHERE typname = 'e_memo_category') THEN
    CREATE TYPE e_memo_category AS ENUM (
      'general',       -- Nota general de seguimiento
      'referral',      -- Derivación / Interconsulta interdepartamental
      'clinical_note', -- Observación clínica / conductual
      'administrative',-- Asunto administrativo / familiar
      'follow_up'      -- Seguimiento a acuerdo previo
    );
  END IF;
END $$;

-- -----------------------------------------------------------------------------
-- 2. Tabla Principal: resident_memos
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.resident_memos (
  id              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id       INTEGER REFERENCES public.organizations (id) ON DELETE SET NULL,
  older_adult_id  INTEGER NOT NULL REFERENCES public.older_adult (id) ON DELETE CASCADE,
  author_id       INTEGER NOT NULL REFERENCES public.users (id) ON DELETE RESTRICT,

  -- Enrutamiento selectivo (@usuario o #departamento/rol)
  target_user_id  INTEGER REFERENCES public.users (id) ON DELETE SET NULL,
  target_role_id  INTEGER REFERENCES public.roles (id) ON DELETE SET NULL,

  -- Hilo de respuestas / Seguimiento directo (Árbol jerárquico)
  parent_memo_id  INTEGER REFERENCES public.resident_memos (id) ON DELETE CASCADE,

  -- Contenido y taxonomía
  content         TEXT NOT NULL,
  category        e_memo_category NOT NULL DEFAULT 'general',
  visibility      e_memo_visibility NOT NULL DEFAULT 'public',
  status          e_memo_status NOT NULL DEFAULT 'open',
  urgency         e_memo_urgency NOT NULL DEFAULT 'routine',

  -- Adjuntos estructurados [{url, name, size, type}]
  attachments     JSONB NOT NULL DEFAULT '[]'::jsonb,

  -- Trazabilidad y ciclo de vida
  is_edited       BOOLEAN NOT NULL DEFAULT FALSE,
  resolved_at     TIMESTAMPTZ,
  resolved_by     INTEGER REFERENCES public.users (id) ON DELETE SET NULL,
  created_at      TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at      TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- -----------------------------------------------------------------------------
-- 3. Tabla de Acuses de Recibo y Lecturas (resident_memo_acknowledgments)
-- Permite saber cuándo un usuario asignado abrió o dio por recibida una derivación
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.resident_memo_acknowledgments (
  id              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  memo_id         INTEGER NOT NULL REFERENCES public.resident_memos (id) ON DELETE CASCADE,
  user_id         INTEGER NOT NULL REFERENCES public.users (id) ON DELETE CASCADE,
  acknowledged_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  notes           TEXT,
  CONSTRAINT uq_memo_user_acknowledgment UNIQUE (memo_id, user_id)
);

-- -----------------------------------------------------------------------------
-- 4. Índices para Alto Rendimiento
-- -----------------------------------------------------------------------------
-- Carga ultrarrápida del timeline del residente
CREATE INDEX IF NOT EXISTS idx_memos_older_adult_created
  ON public.resident_memos (older_adult_id, created_at DESC);

-- Consultas de autoría
CREATE INDEX IF NOT EXISTS idx_memos_author
  ON public.resident_memos (author_id);

-- Bandeja de entrada: derivaciones dirigidas a un usuario específico
CREATE INDEX IF NOT EXISTS idx_memos_target_user_status
  ON public.resident_memos (target_user_id, status)
  WHERE target_user_id IS NOT NULL;

-- Bandeja de entrada: derivaciones dirigidas a un rol/departamento
CREATE INDEX IF NOT EXISTS idx_memos_target_role_status
  ON public.resident_memos (target_role_id, status)
  WHERE target_role_id IS NOT NULL;

-- Reconstrucción de hilos de conversación
CREATE INDEX IF NOT EXISTS idx_memos_parent_memo
  ON public.resident_memos (parent_memo_id)
  WHERE parent_memo_id IS NOT NULL;

-- Filtrado por estado general y categoría
CREATE INDEX IF NOT EXISTS idx_memos_status
  ON public.resident_memos (status);

CREATE INDEX IF NOT EXISTS idx_memos_category
  ON public.resident_memos (category);

-- Filtrado por tenant si multi-tenancy está activo
CREATE INDEX IF NOT EXISTS idx_memos_tenant_id
  ON public.resident_memos (tenant_id)
  WHERE tenant_id IS NOT NULL;

-- Índices para acuses de recibo
CREATE INDEX IF NOT EXISTS idx_memo_ack_memo_id
  ON public.resident_memo_acknowledgments (memo_id);

CREATE INDEX IF NOT EXISTS idx_memo_ack_user_id
  ON public.resident_memo_acknowledgments (user_id);

-- -----------------------------------------------------------------------------
-- 5. Trigger de actualización automática de timestamp (updated_at)
-- -----------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.trg_set_timestamp_memos()
RETURNS TRIGGER AS $$
BEGIN
  NEW.updated_at = CURRENT_TIMESTAMP;
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trg_resident_memos_updated_at ON public.resident_memos;
CREATE TRIGGER trg_resident_memos_updated_at
  BEFORE UPDATE ON public.resident_memos
  FOR EACH ROW
  EXECUTE FUNCTION public.trg_set_timestamp_memos();

-- -----------------------------------------------------------------------------
-- 6. Asignación de Permisos de Rol de Aplicación (sigha_app) si existe
-- -----------------------------------------------------------------------------
DO $$
BEGIN
  IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'sigha_app') THEN
    GRANT SELECT, INSERT, UPDATE, DELETE ON public.resident_memos TO sigha_app;
    GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA public TO sigha_app;
    GRANT SELECT, INSERT, UPDATE, DELETE ON public.resident_memo_acknowledgments TO sigha_app;
  END IF;
END $$;

-- -----------------------------------------------------------------------------
-- 7. Documentación y Metadatos de Tablas
-- -----------------------------------------------------------------------------
COMMENT ON TABLE public.resident_memos IS
  'Bitácora clínica/administrativa de residentes y motor de derivaciones interdepartamentales estilo memos';

COMMENT ON COLUMN public.resident_memos.visibility IS
  'Nivel de visibilidad: public (todo el staff), clinical (áreas de salud), confidential (autor y dirección)';

COMMENT ON COLUMN public.resident_memos.status IS
  'Estado del memo/caso: open (abierto), in_progress (en proceso), resolved (resuelto), archived (archivado)';

COMMENT ON COLUMN public.resident_memos.urgency IS
  'Nivel de urgencia de la derivación: routine, priority, urgent';

COMMENT ON TABLE public.resident_memo_acknowledgments IS
  'Registro de acuses de recibo o confirmación de lectura de derivaciones por parte de profesionales';
