-- 1. Sincronizador bidireccional Estancia <-> Cama <-> Perfil
CREATE OR REPLACE FUNCTION operacion.trg_sincronizar_estancia_cama()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
  IF TG_OP = 'INSERT' OR TG_OP = 'UPDATE' THEN
    IF NEW.fecha_egreso IS NULL THEN
      -- Estancia activa: marcar cama como ocupada y asignar a perfil
      UPDATE operacion.cama SET estado = 'ocupada' WHERE id = NEW.cama_id;
      UPDATE core.perfil SET cama_actual_id = NEW.cama_id WHERE id = NEW.perfil_id;
    ELSE
      -- Estancia finalizada: liberar cama y desvincular de perfil si corresponde
      UPDATE operacion.cama SET estado = 'disponible' WHERE id = NEW.cama_id;
      UPDATE core.perfil SET cama_actual_id = NULL WHERE id = NEW.perfil_id AND cama_actual_id = NEW.cama_id;
    END IF;
  ELSIF TG_OP = 'DELETE' THEN
    UPDATE operacion.cama SET estado = 'disponible' WHERE id = OLD.cama_id;
    UPDATE core.perfil SET cama_actual_id = NULL WHERE id = OLD.perfil_id AND cama_actual_id = OLD.cama_id;
  END IF;
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_sincronizar_cama ON operacion.estancia;
CREATE TRIGGER trg_sincronizar_cama
AFTER INSERT OR UPDATE OR DELETE ON operacion.estancia
FOR EACH ROW EXECUTE FUNCTION operacion.trg_sincronizar_estancia_cama();

-- 2. Validador dinámico de Perfil Digital contra campos obligatorios de la plantilla
CREATE OR REPLACE FUNCTION core.trg_validar_perfil_digital()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
  v_campo RECORD;
  v_valor jsonb;
BEGIN
  FOR v_campo IN
    SELECT c.clave, c.etiqueta, c.tipo
    FROM core.definicion_campo c
    JOIN core.seccion_campo s ON s.id = c.seccion_id
    WHERE s.plantilla_id = NEW.plantilla_id
      AND c.obligatorio = TRUE
      AND c.deleted_at IS NULL
  LOOP
    v_valor := NEW.datos -> v_campo.clave;
    IF v_valor IS NULL OR v_valor = 'null'::jsonb OR (jsonb_typeof(v_valor) = 'string' AND trim(v_valor #>> '{}') = '') THEN
      RAISE EXCEPTION 'El campo obligatorio "%" (%) no puede estar vacío.', v_campo.etiqueta, v_campo.clave
        USING ERRCODE = 'check_violation';
    END IF;
  END LOOP;

  NEW.updated_at = CURRENT_TIMESTAMP;
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_perfil_digital_val ON core.perfil_digital;
CREATE TRIGGER trg_perfil_digital_val
BEFORE INSERT OR UPDATE ON core.perfil_digital
FOR EACH ROW EXECUTE FUNCTION core.trg_validar_perfil_digital();

