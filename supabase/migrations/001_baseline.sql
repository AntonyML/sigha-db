-- Habilitar RLS en tablas con tenant_id
DO $$
DECLARE
  v_tbl RECORD;
BEGIN
  FOR v_tbl IN (
    SELECT table_schema, table_name
    FROM information_schema.columns
    WHERE column_name = 'tenant_id'
      AND table_schema IN ('core', 'clinico', 'operacion', 'seguridad', 'auditoria')
