CREATE OR REPLACE FUNCTION public.uuidv7()
RETURNS uuid
LANGUAGE plpgsql
PARALLEL SAFE
AS $$
DECLARE
  v_time timestamptz := clock_timestamp();
  v_epoch_ms bigint;
  v_bytes bytea;
BEGIN
  v_epoch_ms := (extract(epoch FROM v_time) * 1000)::bigint;
  v_bytes := substring(int8send(v_epoch_ms) FROM 3 FOR 6) || gen_random_bytes(10);
  v_bytes := set_byte(v_bytes, 6, (get_byte(v_bytes, 6) & 15) | 112); -- versión 7
  v_bytes := set_byte(v_bytes, 8, (get_byte(v_bytes, 8) & 63) | 128); -- variante RFC
  RETURN encode(v_bytes, 'hex')::uuid;
END;
$$;

CREATE OR REPLACE FUNCTION public.set_updated_at()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
  NEW.updated_at = CURRENT_TIMESTAMP;
  RETURN NEW;
END;
$$;

