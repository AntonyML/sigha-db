CREATE OR REPLACE VIEW analitica.v_resumen_residentes AS
SELECT
  p.id AS persona_id,
  pr.id AS persona_rol_id,
  perf.id AS perfil_id,
  perf.tenant_id,
  p.nombre,
  p.primer_apellido,
  p.segundo_apellido,
  p.nombre_completo,
  p.fecha_nacimiento,
  DATE_PART('year', AGE(CURRENT_DATE, p.fecha_nacimiento))::INTEGER AS edad,
  p.sexo,
  p.foto_url,
  doc.tipo AS documento_tipo,
  doc.numero AS documento_numero,
  perf.estado AS perfil_estado,
  perf.fecha_ingreso,
  c.codigo AS cama_codigo,
  hab.numero AS habitacion_numero,
  pab.nombre AS pabellon_nombre,
  pd.datos AS perfil_digital_datos
FROM core.persona p
JOIN core.persona_rol pr ON pr.persona_id = p.id AND pr.rol = 'RESIDENTE'
JOIN core.perfil perf ON perf.persona_rol_id = pr.id
LEFT JOIN core.perfil_digital pd ON pd.perfil_id = perf.id
LEFT JOIN core.documento_identidad doc ON doc.persona_id = p.id AND doc.es_principal = TRUE
LEFT JOIN operacion.cama c ON c.id = perf.cama_actual_id
LEFT JOIN operacion.habitacion hab ON hab.id = c.habitacion_id
LEFT JOIN operacion.pabellon pab ON pab.id = hab.pabellon_id
WHERE p.deleted_at IS NULL AND perf.deleted_at IS NULL;

