-- Limpieza controlada de tablas, vistas y tipos de aplicación legacy en 'public'
-- Preserva extensiones (postgis, partman, cron) y esquema 'auth'
DO $$
DECLARE
  r RECORD;
BEGIN
  -- 1. Eliminar vistas legacy de aplicación
  FOR r IN (
    SELECT c.relname
    FROM pg_class c
    JOIN pg_namespace n ON n.oid = c.relnamespace
    WHERE n.nspname = 'public'
      AND c.relkind = 'v'
      AND NOT EXISTS (
        SELECT 1 FROM pg_depend d WHERE d.objid = c.oid AND d.deptype = 'e'
      )
  ) LOOP
    EXECUTE 'DROP VIEW IF EXISTS public.' || quote_ident(r.relname) || ' CASCADE;';
  END LOOP;

  -- 2. Eliminar tablas base legacy de aplicación
  FOR r IN (
    SELECT c.relname
    FROM pg_class c
    JOIN pg_namespace n ON n.oid = c.relnamespace
    WHERE n.nspname = 'public'
      AND c.relkind = 'r'
      AND NOT EXISTS (
        SELECT 1 FROM pg_depend d WHERE d.objid = c.oid AND d.deptype = 'e'
      )
  ) LOOP
    EXECUTE 'DROP TABLE IF EXISTS public.' || quote_ident(r.relname) || ' CASCADE;';
  END LOOP;

  -- 3. Eliminar tipos/enums legacy de aplicación
  FOR r IN (
    SELECT t.typname
    FROM pg_type t
    JOIN pg_namespace n ON n.oid = t.typnamespace
    WHERE n.nspname = 'public'
      AND t.typtype = 'e'
      AND NOT EXISTS (
        SELECT 1 FROM pg_depend d WHERE d.objid = t.oid AND d.deptype = 'e'
      )
  ) LOOP
    EXECUTE 'DROP TYPE IF EXISTS public.' || quote_ident(r.typname) || ' CASCADE;';
  END LOOP;
END $$;

