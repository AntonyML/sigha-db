-- ENUM para los módulos del sistema
CREATE TYPE e_permission_module AS ENUM (
  'users',
  'roles',
  'permissions',
  'dashboard',
  'virtualFiles',
  'audits',
  'programs',
  'vaccines',
  'subPrograms',
  'entranceExit',
  'twoFactor',
  'nursing',
  'physiotherapy',
  'psychology',
  'socialWork',
  'clinicalHistory',
  'clinicalMedication',
  'medicalRecords',
  'emergencyContacts',
  'olderAdultFamily',
  'olderAdultUpdates',
  'specializedAreas',
  'specializedAppointments'
);

-- ENUM para las acciones
CREATE TYPE e_permission_action AS ENUM ('view', 'create', 'edit', 'delete');

-- -----------------------------------------------------------------------------
-- permissions  (catálogo de permisos disponibles en el sistema)
-- -----------------------------------------------------------------------------
CREATE TABLE permissions (
  id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  p_name      VARCHAR(100) NOT NULL,
  p_description VARCHAR(255) NOT NULL DEFAULT '',
  p_module    e_permission_module NOT NULL,
  p_action    e_permission_action NOT NULL,
  p_enabled   BOOLEAN NOT NULL DEFAULT TRUE,
  created_at  TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at  TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT uq_permission_module_action UNIQUE (p_module, p_action)
);

CREATE INDEX idx_permission_module  ON permissions (p_module);
CREATE INDEX idx_permission_action  ON permissions (p_action);
CREATE INDEX idx_permission_enabled ON permissions (p_enabled);

DROP TRIGGER IF EXISTS trg_permissions_updated_at ON permissions;
CREATE TRIGGER trg_permissions_updated_at
BEFORE UPDATE ON permissions
FOR EACH ROW EXECUTE FUNCTION set_updated_at();

-- -----------------------------------------------------------------------------
-- role_permissions  (qué permisos tiene cada rol — por defecto todos habilitados)
-- -----------------------------------------------------------------------------
CREATE TABLE role_permissions (
  id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  role_id       INTEGER NOT NULL,
  permission_id INTEGER NOT NULL,
  rp_granted    BOOLEAN NOT NULL DEFAULT TRUE,
  created_at    TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at    TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_rp_role       FOREIGN KEY (role_id)       REFERENCES roles       (id) ON DELETE CASCADE,
  CONSTRAINT fk_rp_permission FOREIGN KEY (permission_id) REFERENCES permissions (id) ON DELETE CASCADE,
  CONSTRAINT uq_role_permission UNIQUE (role_id, permission_id)
);

CREATE INDEX idx_rp_role       ON role_permissions (role_id);
CREATE INDEX idx_rp_permission ON role_permissions (permission_id);
CREATE INDEX idx_rp_granted    ON role_permissions (rp_granted);

DROP TRIGGER IF EXISTS trg_role_permissions_updated_at ON role_permissions;
CREATE TRIGGER trg_role_permissions_updated_at
BEFORE UPDATE ON role_permissions
FOR EACH ROW EXECUTE FUNCTION set_updated_at();

