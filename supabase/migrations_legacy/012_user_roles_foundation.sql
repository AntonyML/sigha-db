-- =============================================================================
-- 010_user_roles_foundation.sql
-- Foundation for future multi-role support.
-- Adds a user_roles bridge table (N:M between users and roles) while
-- preserving the legacy users.role_id column and all existing data.
-- No behavioral change: the backend keeps reading users.role_id.
-- Idempotent: safe to run on a populated database and safe to re-run.
-- Run after 009.
-- =============================================================================

-- -----------------------------------------------------------------------------
-- 1. Bridge table users <-> roles (N:M foundation).
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS user_roles (
  id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id     INTEGER NOT NULL,
  role_id     INTEGER NOT NULL,
  is_primary  BOOLEAN NOT NULL DEFAULT FALSE,
  assigned_by INTEGER,
  created_at  TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_user_roles_user       FOREIGN KEY (user_id)     REFERENCES users (id) ON DELETE CASCADE,
  CONSTRAINT fk_user_roles_role       FOREIGN KEY (role_id)     REFERENCES roles (id) ON DELETE CASCADE,
  CONSTRAINT fk_user_roles_assigned_by FOREIGN KEY (assigned_by) REFERENCES users (id) ON DELETE SET NULL,
  CONSTRAINT uq_user_roles_user_role UNIQUE (user_id, role_id)
);

-- -----------------------------------------------------------------------------
-- 2. Indexes.
--    idx_user_roles_user / role / assigned_by: standard join indexes.
--    idx_user_roles_primary: partial UNIQUE index enforcing "at most one
--    primary role per user" (PostgreSQL pattern for filtered uniqueness).
-- -----------------------------------------------------------------------------
CREATE INDEX IF NOT EXISTS idx_user_roles_user        ON user_roles (user_id);
CREATE INDEX IF NOT EXISTS idx_user_roles_role        ON user_roles (role_id);
CREATE INDEX IF NOT EXISTS idx_user_roles_assigned_by ON user_roles (assigned_by);

CREATE UNIQUE INDEX IF NOT EXISTS idx_user_roles_primary
  ON user_roles (user_id)
  WHERE is_primary = TRUE;

-- -----------------------------------------------------------------------------
-- 3. Backfill: mirror the current users.role_id into user_roles so the
--    foundation is populated and ready for future multi-role use.
--    Each backfilled row is marked is_primary = TRUE.
--    ON CONFLICT DO NOTHING makes the backfill idempotent (safe to re-run).
--    Rows where users.role_id IS NULL are intentionally skipped: those users
--    have no current role and therefore no bridge row to create.
-- -----------------------------------------------------------------------------
INSERT INTO user_roles (user_id, role_id, is_primary, assigned_by, created_at)
SELECT u.id, u.role_id, TRUE, NULL, CURRENT_TIMESTAMP
  FROM users u
 WHERE u.role_id IS NOT NULL
   AND NOT EXISTS (
     SELECT 1 FROM user_roles ur
      WHERE ur.user_id = u.id
        AND ur.role_id = u.role_id
   );

-- End of 010.
