-- -----------------------------------------------------------------------------
-- specialized_area
-- -----------------------------------------------------------------------------
CREATE TABLE specialized_area (
  id              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  sa_name         e_specialized_area_name NOT NULL DEFAULT 'not specified',
  sa_description  TEXT,
  sa_contact_email VARCHAR(256),
  sa_contact_phone VARCHAR(20),
  sa_is_active    BOOLEAN     NOT NULL DEFAULT TRUE,
  create_at       TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  id_manager      INTEGER,
  CONSTRAINT fk_area_manager FOREIGN KEY (id_manager) REFERENCES users (id) ON DELETE SET NULL
);

CREATE INDEX idx_area_name  ON specialized_area (sa_name);
CREATE INDEX idx_area_email ON specialized_area (sa_contact_email);

