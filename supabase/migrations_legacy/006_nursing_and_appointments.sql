-- -----------------------------------------------------------------------------
-- specialized_appointment
-- -----------------------------------------------------------------------------
CREATE TABLE specialized_appointment (
  id                     INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  sa_appointment_date    TIMESTAMPTZ NOT NULL,
  sa_appointment_type    e_appointment_type    NOT NULL DEFAULT 'checkup',
  sa_priority            e_appointment_priority NOT NULL DEFAULT 'medium',
  sa_status              e_appointment_status   NOT NULL DEFAULT 'scheduled',
  sa_notes               TEXT,
  sa_observations        TEXT,
  sa_duration_minutes    SMALLINT,
  sa_next_appointment    TIMESTAMPTZ,
  create_at              TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  id_area                INTEGER NOT NULL,
  id_patient             INTEGER NOT NULL,
  id_staff               INTEGER NOT NULL,
  CONSTRAINT fk_appt_area    FOREIGN KEY (id_area)    REFERENCES specialized_area (id) ON DELETE CASCADE,
  CONSTRAINT fk_appt_patient FOREIGN KEY (id_patient) REFERENCES older_adult       (id) ON DELETE CASCADE,
  CONSTRAINT fk_appt_staff   FOREIGN KEY (id_staff)   REFERENCES users             (id) ON DELETE CASCADE
);

CREATE INDEX idx_appointment_date     ON specialized_appointment (sa_appointment_date);
CREATE INDEX idx_appointment_priority  ON specialized_appointment (sa_priority);
CREATE INDEX idx_appointment_status    ON specialized_appointment (sa_status);
CREATE INDEX idx_appointment_createat ON specialized_appointment (create_at);

-- -----------------------------------------------------------------------------
-- nursing_records
-- -----------------------------------------------------------------------------
CREATE TABLE nursing_records (
  id                INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nr_date           TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  nr_temperature    NUMERIC(4,1),
  nr_blood_pressure VARCHAR(7),
  nr_heart_rate     SMALLINT,
  nr_pain_level     SMALLINT,
  nr_mobility       e_nursing_mobility NOT NULL DEFAULT 'independent',
  nr_appetite       e_nursing_quality  NOT NULL DEFAULT 'regular',
  nr_sleep_quality  e_nursing_quality  NOT NULL DEFAULT 'regular',
  nr_notes          TEXT,
  create_at         TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  id_appointment    INTEGER,
  CONSTRAINT fk_nr_appt FOREIGN KEY (id_appointment) REFERENCES specialized_appointment (id) ON DELETE CASCADE
);

CREATE INDEX idx_nursing_createat ON nursing_records (create_at);

-- -----------------------------------------------------------------------------
-- physiotherapy_sessions
-- -----------------------------------------------------------------------------
CREATE TABLE physiotherapy_sessions (
  id                     INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ps_date                TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  ps_type                e_physio_session_type  NOT NULL DEFAULT 'therapy',
  ps_mobility_level      e_physio_mobility_level NOT NULL DEFAULT 'moderate',
  ps_pain_level          SMALLINT,
  ps_treatment_description TEXT,
  ps_exercise_plan       TEXT,
  ps_progress_notes      TEXT,
  create_at              TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  id_appointment         INTEGER NOT NULL,
  CONSTRAINT fk_ps_appt FOREIGN KEY (id_appointment) REFERENCES specialized_appointment (id) ON DELETE CASCADE
);

CREATE INDEX idx_physiotherapy_createat ON physiotherapy_sessions (create_at);
CREATE INDEX idx_physiotherapy_type     ON physiotherapy_sessions (ps_type);

-- -----------------------------------------------------------------------------
-- psychology_sessions
-- -----------------------------------------------------------------------------
CREATE TABLE psychology_sessions (
  id                   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  psy_date             TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  psy_session_type     e_psy_session_type     NOT NULL DEFAULT 'evaluation',
  psy_mood             e_psy_mood             NOT NULL DEFAULT 'stable',
  psy_cognitive_status e_psy_cognitive_status NOT NULL DEFAULT 'normal',
  psy_observations     TEXT,
  psy_therapy_goal     TEXT,
  psy_progress         TEXT,
  create_at            TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  id_appointment       INTEGER,
  CONSTRAINT fk_psy_appt FOREIGN KEY (id_appointment) REFERENCES specialized_appointment (id) ON DELETE CASCADE
);

CREATE INDEX idx_psychology_createat ON psychology_sessions (create_at);
CREATE INDEX idx_psychology_type     ON psychology_sessions (psy_session_type);

-- -----------------------------------------------------------------------------
-- social_work_reports
-- -----------------------------------------------------------------------------
CREATE TABLE social_work_reports (
  id                    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  sw_date               TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  sw_visit_type         e_sw_visit_type NOT NULL DEFAULT 'interview',
  sw_family_relationship TEXT,
  sw_economic_assessment TEXT,
  sw_social_support     TEXT,
  sw_observations       TEXT,
  sw_recommendations    TEXT,
  create_at             TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  id_appointment        INTEGER,
  CONSTRAINT fk_sw_appt FOREIGN KEY (id_appointment) REFERENCES specialized_appointment (id) ON DELETE CASCADE
);

CREATE INDEX idx_socialwork_createat ON social_work_reports (create_at);
CREATE INDEX idx_socialwork_date     ON social_work_reports (sw_date);

-- -----------------------------------------------------------------------------
-- medical_record
-- -----------------------------------------------------------------------------
CREATE TABLE medical_record (
  id                INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  mr_record_date    TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  mr_summary        TEXT NOT NULL,
  mr_diagnosis      TEXT,
  mr_treatment      TEXT,
  mr_observations   TEXT,
  mr_origin_area    VARCHAR(60) NOT NULL,
  mr_signed_by      VARCHAR(150),
  create_at         TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  id_older_adult    INTEGER NOT NULL,
  id_appointment    INTEGER,
  id_staff          INTEGER,
  CONSTRAINT fk_mr_oa   FOREIGN KEY (id_older_adult) REFERENCES older_adult            (id) ON DELETE CASCADE,
  CONSTRAINT fk_mr_appt FOREIGN KEY (id_appointment) REFERENCES specialized_appointment (id),
  CONSTRAINT fk_mr_user FOREIGN KEY (id_staff)       REFERENCES users                  (id) ON DELETE SET NULL
);

CREATE INDEX idx_medicalrecord_createat ON medical_record (create_at);
CREATE INDEX idx_medicalrecord_date     ON medical_record (mr_record_date);
CREATE INDEX idx_medicalrecord_oa       ON medical_record (id_older_adult);

