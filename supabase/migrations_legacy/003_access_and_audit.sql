-- -----------------------------------------------------------------------------
-- entrances_exits
-- -----------------------------------------------------------------------------
CREATE TABLE entrances_exits (
  id                    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ee_type               e_entrance_exit_type   NOT NULL DEFAULT 'other',
  ee_access_type        e_entrance_exit_access NOT NULL,
  ee_identification     VARCHAR(20),
  ee_name               VARCHAR(50),
  ee_f_last_name        VARCHAR(50),
  ee_s_last_name        VARCHAR(50),
  ee_datetime_entrance  TIMESTAMPTZ,
  ee_datetime_exit      TIMESTAMPTZ,
  ee_close              BOOLEAN     NOT NULL DEFAULT FALSE,
  ee_observations       TEXT,
  create_at             TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_entrancesexits_type          ON entrances_exits (ee_type);
CREATE INDEX idx_entrancesexits_identification ON entrances_exits (ee_identification);
CREATE INDEX idx_entrancesexits_name          ON entrances_exits (ee_name);
CREATE INDEX idx_entrancesexits_createat      ON entrances_exits (create_at);

-- -----------------------------------------------------------------------------
-- digital_record (per-action trail)
-- -----------------------------------------------------------------------------
CREATE TABLE digital_record (
  id             INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  dr_user_id     INTEGER NOT NULL,
  dr_action      e_dr_action NOT NULL DEFAULT 'other',
  dr_table_name  VARCHAR(100),
  dr_record_id   INTEGER,
  dr_description TEXT,
  dr_timestamp   TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_digital_user FOREIGN KEY (dr_user_id) REFERENCES users (id) ON DELETE CASCADE
);

CREATE INDEX idx_digital_name   ON digital_record (dr_table_name);
CREATE INDEX idx_digital_action ON digital_record (dr_action);
CREATE INDEX idx_digital_user   ON digital_record (dr_user_id);

-- -----------------------------------------------------------------------------
-- audit_reports (count of generated audits + details)
-- -----------------------------------------------------------------------------
CREATE TABLE audit_reports (
  id                INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ar_audit_number   INTEGER UNIQUE,
  ar_type           e_audit_type  NOT NULL DEFAULT 'other',
  ar_entity_name    VARCHAR(100),
  ar_entity_id      INTEGER,
  ar_action         e_audit_action NOT NULL DEFAULT 'other',
  ar_old_value      TEXT,
  ar_new_value      TEXT,
  ar_observations   TEXT,
  ar_start_date     TIMESTAMPTZ NOT NULL,
  ar_end_date       TIMESTAMPTZ,
  ar_duration_seconds INTEGER,
  ar_ip_address     VARCHAR(45),
  ar_user_agent     TEXT,
  create_at         TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  id_generator      INTEGER,
  CONSTRAINT fk_audit_user FOREIGN KEY (id_generator) REFERENCES users (id)
);

CREATE INDEX idx_audit_type      ON audit_reports (ar_type);
CREATE INDEX idx_audit_entity    ON audit_reports (ar_entity_name, ar_entity_id);
CREATE INDEX idx_audit_user      ON audit_reports (id_generator);
CREATE INDEX idx_audit_action    ON audit_reports (ar_action);
CREATE INDEX idx_audit_create_at ON audit_reports (create_at);

-- -----------------------------------------------------------------------------
-- notifications + notification_attachments
-- -----------------------------------------------------------------------------
CREATE TABLE notifications (
  id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  n_title     VARCHAR(150) NOT NULL,
  n_message   TEXT NOT NULL,
  n_send_date TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  n_sent      BOOLEAN     NOT NULL DEFAULT FALSE,
  n_status    e_notification_status NOT NULL DEFAULT 'pending',
  create_at   TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  id_sender   INTEGER NOT NULL,
  CONSTRAINT fk_notification_sender FOREIGN KEY (id_sender) REFERENCES users (id)
);

CREATE INDEX idx_notification_title    ON notifications (n_title);
CREATE INDEX idx_notification_date     ON notifications (n_send_date);
CREATE INDEX idx_notification_createat ON notifications (create_at);
CREATE INDEX idx_notification_status   ON notifications (n_status);
CREATE INDEX idx_notification_sender   ON notifications (id_sender);

CREATE TABLE notification_attachment (
  id                 INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  na_file_name       VARCHAR(150) NOT NULL,
  na_file_path       VARCHAR(255) NOT NULL,
  na_file_mime_type  VARCHAR(100) NOT NULL,
  na_file_size_kb    INTEGER      NOT NULL,
  id_notification    INTEGER      NOT NULL,
  CONSTRAINT fk_attachment_notification FOREIGN KEY (id_notification) REFERENCES notifications (id) ON DELETE CASCADE
);

CREATE INDEX idx_attachment_name ON notification_attachment (na_file_name);
CREATE INDEX idx_attachment_path ON notification_attachment (na_file_path);

